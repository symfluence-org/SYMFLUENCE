"""Configuration for native Raven HBV-EC experiments."""

from __future__ import annotations

from typing import Any, Dict, Optional

from pydantic import BaseModel, Field

from symfluence.core.config.models.base import FROZEN_CONFIG
from symfluence.core.modeling.base import AutoGeneratedConfigAdapter


class RavenConfig(BaseModel):
    model_config = FROZEN_CONFIG
    install_path: str = Field(default="default", alias="RAVEN_INSTALL_PATH")
    exe: str = Field(default="Raven", alias="RAVEN_EXE")
    hru_file: str = Field(default="", alias="RAVEN_HRU_FILE")
    glacier_fraction: float = Field(default=0.0, ge=0, le=1, alias="RAVEN_GLACIER_FRACTION")
    glacier_ice_mm: float = Field(default=100000.0, gt=0, alias="RAVEN_GLACIER_ICE_MM")
    params_to_calibrate: str = Field(
        default="RAINSNOW_TEMP,MELT_FACTOR,REFREEZE_FACTOR,HBV_BETA,SOIL_DEPTH,FAST_K,SLOW_K,PERC,TIME_CONC,GLACIER_CORR,GLACIER_K,SNOW_CORR",
        alias="RAVEN_PARAMS_TO_CALIBRATE",
    )
    param_bounds: Optional[Dict[str, Any]] = Field(default=None, alias="RAVEN_PARAM_BOUNDS")
    timeout: int = Field(default=600, alias="RAVEN_TIMEOUT")
    glacier_constraints: bool = Field(default=False, alias="RAVEN_GLACIER_CONSTRAINTS")
    glacier_mb_error_scale: float = Field(default=1.0, gt=0, alias="RAVEN_GLACIER_MB_ERROR_SCALE")


class RavenConfigAdapter(AutoGeneratedConfigAdapter):
    def __init__(self, model_name="RAVEN"):
        super().__init__(model_name)

    def get_config_schema(self):
        return RavenConfig

    def validate(self, config):
        pass
