"""
Ngen Model Configuration.

Provides configuration schema, defaults, transformers, and validation
for the NextGen Framework model.

This module registers Ngen-specific configuration components with the
ModelRegistry, enabling the core config system to remain model-agnostic.

PHASE 2 REFACTORING: This adapter now uses AutoGeneratedConfigAdapter
to auto-generate defaults and transformers from Pydantic Field declarations.
All defaults are maintained in NgenConfig (model_configs.py) for single
source of truth.
"""
from __future__ import annotations

from typing import Any, Dict

from symfluence.core.mixins.config import resolve_config_value
from symfluence.core.modeling.base import AutoGeneratedConfigAdapter, ConfigValidationError

from .config_schema import NGENConfig


class NgenConfigAdapter(AutoGeneratedConfigAdapter):
    """
    Configuration adapter for NGEN model with auto-generated defaults and transformers.

    Defaults and transformers are automatically extracted from NGENConfig
    Pydantic model. Only custom validation logic is implemented here.
    """

    def __init__(self, model_name: str = 'NGEN'):
        super().__init__(model_name)

    @staticmethod
    def _canonical_module_name(module: str) -> str:
        """Normalize user-facing module aliases to canonical NGEN module names.

        Accepts hyphenated/underscored spellings (e.g. ``SAC-SMA``, ``SNOW-17``,
        ``NOAH-OWP``) and maps them to the canonical names used to build the
        ``NGEN_<MODULE>_PARAMS_TO_CALIBRATE`` config keys. This must stay aligned
        with the canonical Pydantic aliases (e.g. ``NGEN_SNOW17_PARAMS_TO_CALIBRATE``)
        and with ``NgenParameterManager._parse_modules_to_calibrate``.
        """
        raw = module.strip().upper()
        collapsed = raw.replace('-', '').replace('_', '')

        # Map collapsed spellings to canonical module names.
        canonical = {
            'SACSMA': 'SACSMA',
            'SNOW17': 'SNOW17',
            'NOAHOWP': 'NOAH',
        }
        return canonical.get(collapsed, raw)

    def get_config_schema(self):
        """Return NGEN Pydantic configuration schema."""
        return NGENConfig

    def validate(self, config: Dict[str, Any]) -> None:
        """Validate Ngen-specific configuration."""
        # Validate calibration modules have parameter lists
        modules_str = resolve_config_value(
            config,
            lambda: config.model.ngen.modules_to_calibrate,
            dict_key='NGEN_MODULES_TO_CALIBRATE',
        )
        if not modules_str:
            return

        modules = modules_str.split(',')
        for module in modules:
            module_name = self._canonical_module_name(module)
            param_key = f'NGEN_{module_name}_PARAMS_TO_CALIBRATE'
            if not config.get(param_key):
                raise ConfigValidationError(
                    f"NGEN configuration incomplete. Module '{module_name}' is selected for "
                    f"calibration but '{param_key}' is empty or missing."
                )

        # Validate calibration modules are a subset of selected modules
        selected_str = resolve_config_value(
            config,
            lambda: config.model.ngen.modules_selected,
            dict_key='NGEN_MODULES_SELECTED',
        )
        selected = {
            self._canonical_module_name(m)
            for m in selected_str.split(',')
            if m.strip()
        }
        calibrate = {
            self._canonical_module_name(m)
            for m in modules_str.split(',')
            if m.strip()
        }
        not_selected = calibrate - selected
        if not_selected:
            raise ConfigValidationError(
                f"NGEN_MODULES_TO_CALIBRATE contains modules not in "
                f"NGEN_MODULES_SELECTED: {not_selected}. Add them to "
                f"NGEN_MODULES_SELECTED or remove them from NGEN_MODULES_TO_CALIBRATE."
            )


# Backward compatibility alias
NGENConfigAdapter = NgenConfigAdapter
