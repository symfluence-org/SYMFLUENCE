"""Minimal ParFlow I/O without pftools: the ``.pfidb`` key database and ``.pfb`` binary grids.

pftools needs a Tcl version check that fails on Tcl 9 and its Python key database is not generated by
every build, so basin mode writes the files itself.

``.pfb`` layout: a big-endian header (x0, y0, z0 as doubles; nx, ny, nz as ints; dx, dy, dz as doubles; the
number of subgrids as an int), then each subgrid as nine ints (ix, iy, iz, nx, ny, nz, rx, ry, rz) followed by
its values with x fastest. The ``mpi1`` AMPS reader also needs ``<file>.dist`` holding the byte offset of each
rank's subgrid, so multi-rank inputs are written in ParFlow's own P x Q x R decomposition.
"""
from __future__ import annotations

import struct
from pathlib import Path
from typing import Dict, List, Tuple, Union

import numpy as np

PathLike = Union[str, Path]


def write_pfidb(path: PathLike, keys: Dict[str, object]) -> None:
    """Write a ParFlow key database: key count, then key length, key, value length, value per key."""
    parts = [str(len(keys))]
    for key, value in keys.items():
        if value is True or value is False:
            text = str(value)
        elif isinstance(value, float):
            text = f'{value:.10g}'
        else:
            text = str(value)
        parts += [str(len(key)), key, str(len(text)), text]
    Path(path).write_text('\n'.join(parts) + '\n')


def split_extent(n: int, parts: int) -> List[Tuple[int, int]]:
    """ParFlow's grid distribution along one axis: (start, size) per piece; the first ``n % parts`` get one extra."""
    size, extra = divmod(n, parts)
    return [(p * size + min(p, extra), size + (p < extra)) for p in range(parts)]


def write_pfb(path: PathLike, values: np.ndarray, dx: float = 1.0, dy: float = 1.0, dz: float = 1.0,
              x0: float = 0.0, y0: float = 0.0, z0: float = 0.0, P: int = 1, Q: int = 1, R: int = 1) -> None:
    """Write ``values`` (indexed [z, y, x]; 1-D or 2-D arrays are padded on the left) split into P x Q x R subgrids.

    Subgrids are written in rank order (rank = p + P*(q + Q*r)) and ``<path>.dist`` records their offsets.
    """
    a = np.asarray(values, dtype='>f8')
    a = a.reshape((1,) * (3 - a.ndim) + a.shape)
    nz, ny, nx = a.shape
    sx, sy, sz = split_extent(nx, P), split_extent(ny, Q), split_extent(nz, R)
    offsets: List[int] = []
    with open(path, 'wb') as f:
        f.write(struct.pack('>3d3i3d i', x0, y0, z0, nx, ny, nz, dx, dy, dz, P * Q * R))
        for r in range(R):
            for q in range(Q):
                for p in range(P):
                    offsets.append(0 if not offsets else f.tell())
                    (ix, lx), (iy, ly), (iz, lz) = sx[p], sy[q], sz[r]
                    f.write(struct.pack('>9i', ix, iy, iz, lx, ly, lz, 0, 0, 0))
                    f.write(a[iz:iz + lz, iy:iy + ly, ix:ix + lx].tobytes())
    Path(str(path) + '.dist').write_text(''.join(f'{o}\n' for o in offsets))


def read_pfb(path: PathLike) -> np.ndarray:
    """Read a ``.pfb`` file (any number of subgrids) into an array indexed [z, y, x]."""
    with open(path, 'rb') as f:
        _x0, _y0, _z0, nx, ny, nz, _dx, _dy, _dz, nsub = struct.unpack('>3d3i3di', f.read(64))
        out = np.zeros((nz, ny, nx))
        for _ in range(nsub):
            ix, iy, iz, sx, sy, sz, _rx, _ry, _rz = struct.unpack('>9i', f.read(36))
            block = np.frombuffer(f.read(8 * sx * sy * sz), '>f8').reshape(sz, sy, sx)
            out[iz:iz + sz, iy:iy + sy, ix:ix + sx] = block
    return out
