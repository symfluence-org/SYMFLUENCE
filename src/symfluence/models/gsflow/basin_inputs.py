"""GSFLOW input files for the real-basin geometry (``gw_grid_mode: basin``).

Writes params.dat, the MODFLOW-NWT packages and the climate-by-HRU forcing for
a :class:`~symfluence.models.gsflow.basin_geometry.BasinGeometry`. The schematic
square-grid path in ``preprocessor.py`` is untouched.
"""
from __future__ import annotations

import logging
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Sequence

import numpy as np
import pandas as pd

from symfluence.core.exceptions import ConfigurationError, FileOperationError, ValidationError

from .basin_geometry import BasinGeometry

logger = logging.getLogger(__name__)

SNAREA_CURVE = [0.05, 0.24, 0.40, 0.53, 0.65, 0.73, 0.80, 0.87, 0.93, 0.97, 1.00]
ACRES_PER_M2 = 1.0 / 4046.8564224
CBH_VARIABLES = ('precip', 'tmax', 'tmin', 'swrad')
STREAM_WIDTH_M = 10.0


def hru_source_ids(elev: Sequence[float], band_size: float, band_ids: Dict[int, int]) -> List[int]:
    """Source forcing hruId per HRU from its elevation band (nearest mapped band)."""
    if not band_ids:
        raise ConfigurationError('climate_hru forcing in basin mode needs GSFLOW_HRU_FORCING_BAND_IDS')
    lows = np.array(sorted(band_ids))
    out = []
    for z in elev:
        low = np.floor(z / band_size) * band_size
        out.append(band_ids[int(lows[np.argmin(np.abs(lows - low))])])
    return out


def load_hru_forcing(path: Path, source_ids: Sequence[int], start: datetime, end: datetime) -> Dict[str, pd.DataFrame]:
    """Daily per-HRU forcing (precip mm, tmax/tmin C, swrad Langley) from
    canonical forcing with an ``hru`` dimension, in ``source_ids`` order."""
    from symfluence.core.modeling.model_ready.forcing_reader import forcing_timestep_seconds, open_canonical_forcing
    files = sorted(Path(path).glob('*.nc'))
    if not files:
        raise FileOperationError(f'No per-HRU forcing NetCDF in {path}')
    names = {'precipitation_flux': 'precip', 'air_temperature': 'temp', 'surface_downwelling_shortwave_flux': 'swrad'}
    parts: Dict[str, List[pd.DataFrame]] = {v: [] for v in names.values()}
    step = None
    for f in files:
        ds = open_canonical_forcing(f)
        try:
            if set(names) - set(ds.data_vars) or 'hru' not in ds.dims:
                raise ValidationError(f'{f.name} lacks per-HRU canonical forcing')
            ids = ds['hruId']
            ids = (ids.isel(time=0) if 'time' in ids.dims else ids).values.astype(int)
            step = step or forcing_timestep_seconds(ds)
            t = pd.DatetimeIndex(ds['time'].values)
            for var, short in names.items():
                parts[short].append(pd.DataFrame(ds[var].transpose('time', 'hru').values, index=t, columns=ids))
        finally:
            ds.close()
    raw = {}
    for short, frames in parts.items():
        df = pd.concat(frames).sort_index()
        df = df[~df.index.duplicated()].loc[str(start):str(end)]
        absent = set(source_ids) - set(df.columns)
        if absent:
            raise ConfigurationError(f'Per-HRU forcing lacks source hruIds {sorted(absent)}')
        raw[short] = df[list(source_ids)]
    temp = raw['temp'] - 273.15
    daily = {'precip': (raw['precip'] * step).resample('D').sum(), 'tmax': temp.resample('D').max(),
             'tmin': temp.resample('D').min(), 'swrad': raw['swrad'].clip(lower=0).resample('D').mean() * 2.0651}
    for name, df in daily.items():
        if df.empty or df.isna().any().any():
            raise ValidationError(f'Per-HRU {name} forcing has gaps between {start} and {end}')
    return daily


def write_cbh(directory: Path, daily: Dict[str, pd.DataFrame]) -> Dict[str, Path]:
    paths = {}
    for name in CBH_VARIABLES:
        df = daily[name]
        p = directory / f'{name}.cbh'
        with open(p, 'w') as f:
            f.write(f'GSFLOW {name} CBH generated by SYMFLUENCE\n{name} {df.shape[1]}\n{"#" * 40}\n')
            for d, row in zip(df.index, df.to_numpy()):
                f.write(f'{d.year} {d.month} {d.day} 0 0 0 ' + ' '.join(f'{v:.4f}' for v in row) + '\n')
        paths[name] = p
    return paths


class _ParamWriter:
    def __init__(self, f):
        self.f = f

    def __call__(self, name, dims, values, dtype=2):
        values = list(np.atleast_1d(values))
        self.f.write(f'####\n{name}\n{len(dims[0])}\n' + ''.join(f'{d}\n' for d in dims[0]) + f'{len(values)}\n{dtype}\n')
        fmt = (lambda v: str(int(v))) if dtype == 1 else (lambda v: f'{float(v):.8g}')
        self.f.write(''.join(fmt(v) + '\n' for v in values))


def write_parameters(path: Path, geo: BasinGeometry, cfg, overrides: Dict[str, dict]) -> Dict[str, int]:
    """Write params.dat for the basin geometry; returns the dimensions."""
    h = geo.hrus
    n = geo.nhru
    nseg = len(geo.segments)
    glacier = cfg.glacier_flag and bool(h.glacier.any())
    if cfg.glacier_flag and not glacier:
        raise ConfigurationError('GSFLOW glacier_flag is set but no glacier HRUs were built')
    ndepl = 2 if cfg.separate_glacier_depletion_curve else 1
    if ndepl == 2 and not glacier:
        raise ConfigurationError('Separate glacier depletion curves need glacier HRUs')
    dims = {'nhru': n, 'ngw': n, 'nssr': n, 'nsub': 1, 'nsegment': nseg, 'nmonths': 12, 'one': 1, 'nobs': 1,
            'ndepl': ndepl, 'ndeplval': 11 * ndepl, 'nrain': 1, 'ntemp': 1, 'nsol': 0, 'nhrucell': len(geo.gvr),
            'ncascade': n, 'ncascdgw': n, 'nreach': len(geo.reaches), 'ngwcell': geo.nrow * geo.ncol}
    land = (h.glacier == 0).to_numpy()
    cov = np.where(land, cfg.cov_type, 0)
    covden = np.where(cov > 0, 1.0, 0.0)
    seg_len = geo.reaches.groupby('seg').length.sum().reindex(geo.segments.seg).to_numpy()
    station_elev = float(np.average(h.elev, weights=h.area_m2))
    with open(path, 'w') as f:
        f.write('PRMS/GSFLOW parameter file generated by SYMFLUENCE (basin geometry)\nVersion: 1.0\n** Dimensions **\n')
        for k, v in dims.items():
            f.write(f'####\n{k}\n{v}\n')
        f.write('** Parameters **\n')
        w = _ParamWriter(f)
        H, M = (['nhru'],), (['nmonths'],)
        for k in ('precip_units', 'temp_units', 'elev_units'):
            w(k, (['one'],), 1, 1)
        w('hru_area', H, h.area_m2 * ACRES_PER_M2)
        w('hru_elev', H, h.elev)
        w('hru_slope', H, [0.15] * n)
        w('hru_lat', H, h.lat)
        w('hru_lon', H, h.lon)
        w('hru_aspect', H, [180.0] * n)
        w('hru_type', H, np.where(land, 1, 4) if glacier else [1] * n, 1)
        w('cov_type', H, cov, 1)
        w('soil_type', H, [2] * n, 1)
        w('hru_percent_imperv', H, [0.0] * n)
        w('hru_segment', H, h.seg, 1)
        w('hru_subbasin', H, [1] * n, 1)
        w('hru_deplcrv', H, np.where(land, 1, 2) if ndepl == 2 else [1] * n, 1)
        w('covden_sum', H, covden * 0.5)
        w('covden_win', H, covden * 0.3)
        for k in ('snow_intcp', 'srain_intcp', 'wrain_intcp'):
            w(k, H, [0.05] * n)
        w('rad_trncf', H, [0.5] * n)
        w('potet_sublim', H, [0.5] * n)
        w('emis_noppt', H, [0.757] * n)
        w('freeh2o_cap', H, [0.05] * n)
        w('cecn_coef', M, [5.0] * 12)
        w('albset_sna', (['one'],), 0.05)
        w('albset_snm', (['one'],), 0.2)
        w('snarea_curve', (['ndeplval'],), SNAREA_CURVE * ndepl)
        w('snarea_thresh', H, [50.0] * n)
        w('transp_beg', H, [4] * n, 1)
        w('transp_end', H, [10] * n, 1)
        w('transp_tmax', H, [1.0] * n)
        w('jh_coef', M, [0.014] * 12)
        w('jh_coef_hru', H, [13.0] * n)
        w('dday_slope', M, [0.30, 0.32, 0.34, 0.36, 0.38, 0.38, 0.36, 0.35, 0.33, 0.31, 0.30, 0.29])
        w('dday_intcp', M, [-20.0, -18.0, -14.0, -10.0, -6.0, -3.0, -2.0, -3.0, -6.0, -12.0, -16.0, -20.0])
        for k, v in (('carea_max', 0.6), ('smidx_coef', 0.01), ('smidx_exp', 0.3), ('imperv_stor_max', 0.05),
                     ('soil_moist_max', 6.0), ('soil_rechr_max_frac', 1.0 / 3.0), ('soil_moist_init_frac', 0.5),
                     ('soil_rechr_init_frac', 0.5), ('soil2gw_max', 0.5), ('slowcoef_lin', 0.015),
                     ('slowcoef_sq', 0.1), ('pref_flow_den', 0.0), ('fastcoef_lin', 0.1), ('fastcoef_sq', 0.1)):
            w(k, H, [v] * n)
        for k, v in (('ssr2gw_rate', 0.1), ('ssr2gw_exp', 1.0), ('ssrcoef_lin', 0.1), ('ssrcoef_sq', 0.1)):
            w(k, (['nssr'],), [v] * n)
        for k, v in (('gwflow_coef', 0.015), ('gwstor_init', 2.0), ('gwstor_min', 0.0), ('gwsink_coef', 0.0),
                     ('gw_seep_coef', 0.02)):
            w(k, (['ngw'],), [v] * n)
        # PRMS 5 ignores tmax_allrain (PRMS4_flag off): all-rain at tmax_allsnow + offset
        w('tmax_allrain_offset', M, [3.3] * 12)
        w('tmax_allsnow', M, [0.0] * 12)
        w('adjmix_rain', M, [1.0] * 12)
        w('tmax_adj', H, [0.0] * n)
        w('tmin_adj', H, [0.0] * n)
        w('rain_adj', M, [1.0] * 12)
        w('snow_adj', M, [1.0] * 12)
        w('tsta_elev', (['ntemp'],), station_elev)
        w('psta_elev', (['nrain'],), station_elev)
        w('hru_tsta', H, [1] * n, 1)
        w('hru_psta', H, [1] * n, 1)
        w('basin_tsta', (['one'],), 1, 1)
        if cfg.forcing_mode == 'climate_hru':
            for k, v in (('rain_cbh_adj', 1.0), ('snow_cbh_adj', 1.0), ('tmax_cbh_adj', 0.0), ('tmin_cbh_adj', 0.0)):
                w(k, (['nhru', 'nmonths'],), [v] * (n * 12))
        if glacier:
            w('glacier_frac_init', H, (~land).astype(float))
            w('tohru', H, h.tohru, 1)
            w('hru_length', H, h.hru_length_km)
            w('hru_width', H, h.hru_width_km)
        segs = geo.segments
        w('tosegment', (['nsegment'],), segs.outseg, 1)
        w('seg_length', (['nsegment'],), seg_len)
        w('K_coef', (['nsegment'],), [0.1] * nseg)
        w('x_coef', (['nsegment'],), [0.2] * nseg)
        w('obsin_segment', (['nsegment'],), [0] * nseg, 1)
        g = geo.gvr
        w('gvr_hru_id', (['nhrucell'],), g.hru_id, 1)
        w('gvr_cell_id', (['nhrucell'],), g.cell_id, 1)
        w('gvr_cell_pct', (['nhrucell'],), g.cell_pct)
        w('gvr_hru_pct', (['nhrucell'],), g.hru_pct)
        for pre, dn in (('hru', 'ncascade'), ('gw', 'ncascdgw')):
            w(f'{pre}_up_id', ([dn],), h.hru_id, 1)
            w(f'{pre}_down_id', ([dn],), [0] * n, 1)
            w(f'{pre}_pct_up', ([dn],), [1.0] * n)
            w(f'{pre}_strmseg_down_id', ([dn],), h.seg, 1)
        w('cascade_tol', (['one'],), 5.0)
        w('cascade_flg', (['one'],), 0, 1)
    if overrides:
        _apply_overrides(path, dims, overrides)
    return dims


def _apply_overrides(path: Path, dims: Dict[str, int], overrides: Dict[str, dict]) -> None:
    """Replace or add parameter blocks (same format as PRMS_PARAMETER_OVERRIDES)."""
    head, body = path.read_text().split('** Parameters **\n', 1)
    blocks = {b.strip().splitlines()[0]: b for b in body.split('####\n') if b.strip()}
    for name, spec in overrides.items():
        dd = spec['dimensions']
        count = int(np.prod([dims[d] for d in dd]))
        values = spec['values'] if isinstance(spec['values'], list) else [spec['values']] * count
        if len(values) != count:
            raise ConfigurationError(f'GSFLOW override {name}: expected {count} values, got {len(values)}')
        blocks[name] = '\n'.join(map(str, [name, len(dd), *dd, count, spec.get('dtype', 2), *values])) + '\n'
    path.write_text(head + '** Parameters **\n' + ''.join('####\n' + b for b in blocks.values()))


def _filled(top: np.ndarray, active: np.ndarray) -> np.ndarray:
    """Inactive cells take the mean active value (MODFLOW still reads them)."""
    return np.where(active, top, np.nanmean(top[active]))


def _internal(arr: np.ndarray, fmt: str) -> str:
    rows = ['  INTERNAL  1  (FREE)  0']
    rows += ['    ' + ' '.join(fmt % v for v in r) for r in arr]
    return '\n'.join(rows) + '\n'


def write_modflow(mf: Path, geo: BasinGeometry, ndays: int, aquifer_thickness: float, initial_recharge: float,
                  thts: float, output_relpath: str, hk: float = 1.0, sy: float = 0.15, strhc1: float = 1.0,
                  manning_n: float = 0.04, ntrail: int = 15, nsets: int = 20) -> None:
    if thts <= sy:
        raise ConfigurationError('GSFLOW saturated water content must exceed specific yield')
    top = _filled(geo.top, geo.active)
    bot = top - aquifer_thickness
    act = geo.active.astype(int)
    (mf / 'modflow.nam').write_text(
        f'LIST  26  {output_relpath}/modflow/gsflow_mf.list\nBAS6   8  modflow/bow.bas\nDIS   11  modflow/bow.dis\n'
        'UPW   35  modflow/bow.upw\nNWT   34  modflow/bow.nwt\nUZF   14  modflow/bow.uzf\nSFR   15  modflow/bow.sfr\n'
        f'OC     9  modflow/bow.oc\nDATA(BINARY)  58  {output_relpath}/modflow/heads.out\n')
    (mf / 'bow.dis').write_text(
        f'# GSFLOW MODFLOW-NWT Discretization (basin grid {geo.nrow}x{geo.ncol}, {geo.cell_size:g} m)\n'
        f'         1         {geo.nrow}         {geo.ncol}         2         4         2\n 0\n'
        f'  CONSTANT  {geo.cell_size:.1f}\n  CONSTANT  {geo.cell_size:.1f}\n'
        + _internal(top, '%.2f') + _internal(bot, '%.2f')
        + f'    1.0  1  1.0  SS\n    {float(ndays):.1f}  {ndays}  1.0  TR\n')
    (mf / 'bow.bas').write_text('# GSFLOW Basic Package (basin grid)\nFREE\n' + _internal(act, '%d')
                                + '  -999.99\n' + _internal(top - 5.0, '%.2f'))
    (mf / 'bow.upw').write_text('# GSFLOW UPW Package (basin grid)\n  0  -9999.0  0  1\n  1\n  0\n  1.0\n  0\n  0\n'
                                f'  CONSTANT  {hk:.6e}\n  CONSTANT  {hk:.6e}\n  CONSTANT  1.0e-05\n'
                                f'  CONSTANT  {sy:.6e}\n')
    # Tolerances scale with cell size: 1 m3/day on km-scale cells (~1e-4 mm/day)
    # made NWT fail to converge for plausible parameters. 0.05 mm/day per cell.
    fluxtol = max(1.0, geo.cell_size ** 2 * 5e-5)
    (mf / 'bow.nwt').write_text(f'# GSFLOW NWT Solver\n1.0E-2  {fluxtol:.1f}  500  1.0E-5  1  0  1  COMPLEX\n')
    (mf / 'bow.uzf').write_text(
        f'# GSFLOW UZF Package (basin grid)\n  1  1  1  0  0  0  {ntrail}  {nsets}  0  1.0\n'
        + _internal(act, '%d') + _internal(geo.cell_seg, '%d')
        + f'  CONSTANT  {hk:.6e}\n  CONSTANT  3.5\n  CONSTANT  {thts:.8g}\n'
        + f'  {int(act.sum())}\n  CONSTANT  {initial_recharge:.10g}\n  -1\n')
    r = geo.reaches
    nseg = len(geo.segments)
    lines = ['# GSFLOW SFR Package (basin river network)', 'OPTIONS', 'REACHINPUT', 'TRANSROUTE', 'END',
             f'    {len(r)}  {nseg}  0  0  86400.0  0.0001  -1  0  3  10  1  40  1  4  0.75  0.0001']
    for _, x in r.iterrows():
        lines.append(f'    1  {int(x.row)}  {int(x.col)}  {int(x.seg)}  {int(x.ireach)}  {x.length:.1f}  '
                     f'{x.strtop:.2f}  {x.slope:.6f}  1.0  {strhc1:.6g}  0.30  0.20  3.5  0.3')
    lines.append(f'    {nseg}  0  0')
    for _, s in geo.segments.iterrows():
        lines.append(f'    {int(s.seg)}  1  {int(s.outseg)}  0  0.0  0.0  0.0  0.0  {manning_n:.4f}')
        lines.append(f'  {STREAM_WIDTH_M:.1f}')
        lines.append(f'  {STREAM_WIDTH_M:.1f}')
    lines.append('   -1  0  0')
    (mf / 'bow.sfr').write_text('\n'.join(lines) + '\n')
    (mf / 'bow.oc').write_text('# GSFLOW Output Control\nHEAD PRINT FORMAT  0\nHEAD SAVE UNIT 58\nPERIOD  1 STEP  1\n'
                               f'  SAVE HEAD\n  SAVE BUDGET\nPERIOD  2 STEP  {ndays}\n  SAVE HEAD\n  SAVE BUDGET\n')


def statvars(geo: BasinGeometry, glacier: bool, cryosphere: bool) -> List[tuple]:
    """Statistic variables: discharge/budget terms plus cryosphere HRU states."""
    # basin_storage is PRMS-only (basin_sum); GSFLOW reports storage in gsflow.csv.
    out = [(v, 1) for v in ('basin_cfs', 'basin_actet', 'basin_ppt', 'basin_snowmelt', 'basin_pweqv')]
    if glacier:
        out += [(v, 1) for v in ('basin_gl_storage', 'basin_gl_ice_melt', 'basin_glacrevap')]
    if glacier or cryosphere:
        for name in ('pkwater_equiv', 'glacier_frac', 'snowcov_area'):
            out += [(name, i) for i in range(1, geo.nhru + 1)]
    return out
