"""Design-based Sobol / Morris on the Ishigami function, through the real path.

The design is generated by SALib inside ``SensitivityAnalyzer``, every point is
pushed through ``BaseModelOptimizer.evaluate_design`` (batched population
evaluation with penalty handling) and the indices are estimated from those
responses -- the same path a model run takes, with the model replaced by the
Ishigami function.
"""
from __future__ import annotations

import logging
import math
from types import SimpleNamespace

import numpy as np
import pandas as pd
import pytest

pytest.importorskip("SALib")

from symfluence.core.calibration.optimizers.base_model_optimizer import BaseModelOptimizer
from symfluence.core.constants import ModelDefaults
from symfluence.evaluation.sensitivity_analysis import SensitivityAnalyzer, design_size

pytestmark = pytest.mark.unit

A, B = 7.0, 0.1
# Analytic indices of the Ishigami function on [-pi, pi]^3
_V1 = 0.5 * (1 + B * math.pi ** 4 / 5) ** 2
_V2 = A ** 2 / 8
_V13 = B ** 2 * math.pi ** 8 * (1 / 18 - 1 / 50)
_V = _V1 + _V2 + _V13
S1 = np.array([_V1 / _V, _V2 / _V, 0.0])
ST = np.array([(_V1 + _V13) / _V, _V2 / _V, _V13 / _V])


def ishigami(x01: np.ndarray) -> np.ndarray:
    x = -math.pi + 2 * math.pi * x01
    return np.sin(x[:, 0]) + A * np.sin(x[:, 1]) ** 2 + B * x[:, 2] ** 4 * np.sin(x[:, 0])


def _fake_optimizer(fail_every: int = 0):
    """Stand-in exposing what evaluate_design uses; each 'run' is Ishigami."""
    calls = []

    def evaluate_population(population, iteration=0):
        calls.append(population.shape[0])
        y = ishigami(population)
        if fail_every:
            y[::fail_every] = ModelDefaults.PENALTY_SCORE
        return y

    stub = SimpleNamespace(
        param_manager=SimpleNamespace(all_param_names=['x1', 'x2', 'x3']),
        population_size=64,
        DEFAULT_PENALTY_SCORE=ModelDefaults.PENALTY_SCORE,
        logger=logging.getLogger('test_sa_design'),
        _get_config_value=lambda accessor, default=None, dict_key=None: 4,
        _evaluate_population=evaluate_population,
    )
    stub.evaluate_design = lambda design, batch_size=None: BaseModelOptimizer.evaluate_design(
        stub, design, batch_size)
    return stub, calls


def _analyzer(tmp_path, **cfg):
    config = {
        'SYMFLUENCE_DATA_DIR': str(tmp_path), 'DOMAIN_NAME': 'ishigami',
        'EXPERIMENT_ID': 'sa', 'SENSITIVITY_MAX_EVALUATIONS': 50000, **cfg,
    }
    return SensitivityAnalyzer(config, logging.getLogger('test_sa_design'))


def test_sobol_on_ishigami_recovers_interactions(tmp_path):
    analyzer = _analyzer(tmp_path, SENSITIVITY_METHODS=['sobol'], SENSITIVITY_SOBOL_N=4096)
    opt, calls = _fake_optimizer()
    out = analyzer.run_design_analysis(['x1', 'x2', 'x3'], opt.evaluate_design, seed=1)

    assert sum(calls) == design_size('sobol', 3, sobol_n=4096)
    assert max(calls) == 64  # evaluated in population-sized batches
    np.testing.assert_allclose(out['Sobol_S1'].to_numpy(), S1, atol=0.05)
    np.testing.assert_allclose(out['Sobol_ST'].to_numpy(), ST, atol=0.05)
    # x3 acts only through its interaction with x1: S_T >> S_1
    assert out.loc['x3', 'Sobol_ST'] - out.loc['x3', 'Sobol_S1'] > 0.15
    assert not np.allclose(out['Sobol_ST'], out['Sobol_S1'], atol=0.05)
    saved = pd.read_csv(tmp_path / 'domain_ishigami' / 'reporting' / 'sensitivity_analysis'
                        / 'sa' / 'all_sensitivity_results.csv', index_col=0)
    assert list(saved.columns) == ['Sobol_S1', 'Sobol_ST']


def test_morris_ranks_ishigami_inputs(tmp_path):
    analyzer = _analyzer(tmp_path, SENSITIVITY_METHODS=['morris'],
                         SENSITIVITY_MORRIS_TRAJECTORIES=50)
    opt, calls = _fake_optimizer()
    out = analyzer.run_design_analysis(['x1', 'x2', 'x3'], opt.evaluate_design, seed=2)
    assert sum(calls) == design_size('morris', 3, morris_trajectories=50)
    # x3 has a nonlinear/interaction effect: sigma comparable to mu*
    assert out.loc['x3', 'Morris_sigma'] > 0.5 * out.loc['x3', 'Morris_mu_star']
    assert (out['Morris_mu_star'] > 0).all()


def test_failed_runs_are_reported_not_used_as_penalty(tmp_path, caplog):
    analyzer = _analyzer(tmp_path, SENSITIVITY_METHODS=['sobol'], SENSITIVITY_SOBOL_N=256)
    opt, _ = _fake_optimizer(fail_every=50)
    caplog.set_level(logging.WARNING)
    out = analyzer.run_design_analysis(['x1', 'x2', 'x3'], opt.evaluate_design, seed=3)
    assert 'sensitivity design runs failed' in caplog.text
    # A -9999 penalty in the response would swamp the variance (|S| >> 1)
    assert out['Sobol_ST'].abs().max() < 2


def test_budget_guard_refuses_oversized_design(tmp_path):
    analyzer = _analyzer(tmp_path, SENSITIVITY_METHODS=['sobol'], SENSITIVITY_SOBOL_N=1024,
                         SENSITIVITY_MAX_EVALUATIONS=100)
    opt, calls = _fake_optimizer()
    with pytest.raises(ValueError, match='SENSITIVITY_MAX_EVALUATIONS'):
        analyzer.run_design_analysis(['x1', 'x2', 'x3'], opt.evaluate_design)
    assert calls == []


def test_analysis_manager_runs_design_through_model_optimizer(tmp_path, monkeypatch):
    """The workflow step builds the model's optimizer and evaluates the design with it."""
    from symfluence.evaluation.analysis_manager import AnalysisManager

    mgr = AnalysisManager.__new__(AnalysisManager)
    mgr._config = {
        'SYMFLUENCE_DATA_DIR': str(tmp_path), 'DOMAIN_NAME': 'ishigami', 'EXPERIMENT_ID': 'sa',
        'SENSITIVITY_METHODS': ['morris'], 'SENSITIVITY_MORRIS_TRAJECTORIES': 4, 'RANDOM_SEED': 5,
    }
    mgr.logger = logging.getLogger('test_sa_manager')
    mgr.reporting_manager = None
    opt, calls = _fake_optimizer()
    opt.cleanup = lambda: calls.append('cleanup')
    monkeypatch.setattr(mgr, '_create_model_optimizer', lambda model: opt)
    monkeypatch.setattr(mgr, '_find_optimization_results', lambda model: None)

    out = mgr._run_generic_sensitivity_analysis('FAKE')
    assert list(out.columns) == ['Morris_mu_star', 'Morris_sigma']
    assert sum(c for c in calls if c != 'cleanup') == design_size('morris', 3, morris_trajectories=4)
    assert calls[-1] == 'cleanup'
